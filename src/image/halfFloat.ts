/**
 * half-float の加算累積。**composer のバッファは `HalfFloatType` なので、
 * 加算合成はここで起きていることをそのまま被る。**
 *
 * ## SPEC §4.6 の 2 行を Phase 1b で差し替えた
 *
 * 初版は「**天井は 0.03125 = 2⁻⁵**、停止点は n に依らない」と書いていた。
 * 後半は真だが、前半は **δ ≈ 1.5e−5 における 1 標本**にすぎない。実測（`Float16Array`）:
 *
 * | δ | 実測停止値 | `2048·δ` | 直上の 2 冪 |
 * |---|---|---|---|
 * | 9.537e−7 | 0.001953125 | 0.0019531 | ✓ |
 * | 1.526e−5 | **0.03125** | 0.03125 | ✓ |
 * | 1.530e−5 | **0.0625** | 0.0313344 | ✓ |
 * | 1.000e−3 | 4 | 2.048 | ✓ |
 * | 1.000e+0 | 2048 | 2048 | ✓ |
 *
 * **正しい法則は「天井 = `2048·δ` 以上の最小の 2 冪」。** `A + δ` は
 * `δ = ulp(A)/2` で ties-to-even により丸め戻るので、仮数 10 bit ＝ `ulp(A) = A·2⁻¹⁰`
 * より `A = 2048·δ` が停止点になる。0.03125 はその δ での値でしかない。
 *
 * ## 「約 3% 暗く出る」も偽（実測）
 *
 * 初版は「`dimLevel = 0` の平均色はリニア光で約 3% 暗く出る見込み」と書いていた。
 * **符号も大きさも δ と ulp の 2 進的な関係で決まり、単調でも常に undershoot でもない。**
 * 目標 0.21586（sRGB 128）を n 個に割って足した実測:
 *
 * | n | 合計 | 誤差 |
 * |---|---|---|
 * | 256 | 0.218262 | **+1.11%** |
 * | 378 | 0.219849 | **+1.85%** |
 * | 489 | 0.222168 | **+2.92%** |
 * | 512 | 0.205200 | **−4.94%** |
 * | 2048 | 0.234985 | **+8.86%** |
 * | 3537 | 0.125000 | **−42.09%**（天井で停止） |
 * | 89,208 | 0.007813 | **−96.38%** |
 *
 * 最後の 2 行が Phase 1b の設計を決めている ── **格子（89,208 点）のまま
 * `dimLevel = 0` へ潰すと、加算が天井で止まって 96% 消える。**
 * 列平均バッファが要るのは「丸め誤差 3%」のためではなく、これのためである。
 *
 * ## 予算（ΔE00 換算・グレー軸）—— **Phase 2b で作り直した**
 *
 * ### この表は 2 度、間違った丸めモードで作られていた
 *
 * 上の実測も下の予算も `Float16Array`、つまり **round-to-nearest** で計算していた。
 * Phase 2b の `blendProbe`（作品を通さず、規定した値を GPU の加算合成へ直接積む器具）は、
 * **ブレンドユニットが最近接ではなく 0 方向へ切り捨てる**ことを 6/6 の厳密一致で示した
 * （`image/blendModel.ts`）。最近接は**不偏**、切り捨ては**片側にしか外れない** ──
 * だから深度が増えると誤差が打ち消し合わず、系統的に暗くなる。
 *
 * | 深度 n | RN の誤差（旧） | **RTZ の誤差（実機）** | **RTZ の ΔE00** | 旧 ΔE00 |
 * |---|---|---|---|---|
 * | 16 | +0.151% | **−0.188%** | **0.042** | — |
 * | 64 | +0.490% | **−1.150%** | **0.260** | — |
 * | 128 | +0.886% | **−3.185%** | **0.726** | 0.324 |
 * | 256 | +1.112% | **−7.427%** | **1.731** | 0.622 |
 * | 378 | +1.848% | **−7.709%** | **1.799** | — |
 * | **512** | −4.939% | **−10.311%** | **2.439** | **1.364** |
 * | 1024 | +1.961% | **−21.847%** | **5.476** | 2.506 |
 * | 2048 | +8.860% | **−42.092%** | **11.418** | 4.376 |
 *
 * **`LINE_MAX_POINTS = 512` はいまも予算 3.0 の内側だが、余裕は 1.364 ではなく 2.439** ──
 * 信じていたより **1.8 倍**きわどい。そして Phase 2a が潰れた軸を CPU 側で先に畳んで
 * `dimLevel = 0` の深度を 378 → 1 にした判断は、この表で**より強く正当化される**
 * （378 の 1.799 が 1 の 0.004 になる）。
 *
 * ### これが §4.6 訂正 4 の矛盾を解く
 *
 * 監査の fp16 逐次丸めシミュレーションが「1% 未満」を出し、実測が「−5.2%」だった。
 * **両方とも正しかった** ── シミュレーションは最近接で、実機は切り捨てである。
 * 実測が常に undershoot で、深度と項の大きさに比例していたのも、切り捨ての性質そのもの。
 */

import { f16TruncateToZero } from './blendModel';

/** `A + δ` が丸め戻って停止する値。`2048·δ` 以上の最小の 2 冪（実測 15/15 一致） */
export function f16SaturationCeiling(delta: number): number {
  if (!(delta > 0)) return Number.POSITIVE_INFINITY;
  return Math.pow(2, Math.ceil(Math.log2(2048 * delta)));
}

/**
 * 目標値 `value` を `n` 回の等分割で half-float バッファへ足したときの合計。
 *
 * **実際の加算をそのまま回す**（閉形式で近似しない）── 誤差の符号は
 * δ と ulp の 2 進的な関係で決まるので、丸めの規則を書き写した式では再現できない。
 */
export function f16Accumulate(value: number, n: number): number {
  const buf = new Float16Array(1);
  const delta = value / n;
  for (let i = 0; i < n; i++) buf[0] = buf[0] + delta;
  return buf[0];
}

/** 相対誤差。正なら overshoot ── **「暗くなる」と決めつけない** */
export function f16RelativeError(value: number, n: number): number {
  if (!(value > 0)) return 0;
  return (f16Accumulate(value, n) - value) / value;
}

/**
 * **実機の丸めモードで積む**（Phase 2b）。`f16Accumulate` の切り捨て版。
 *
 * `blendProbe` が実測で選んだのは round-to-nearest ではなく **0 方向への切り捨て**なので、
 * 予算を見積もるときはこちらを使う。`f16Accumulate` は残す ──
 * 「監査のモデルではこうなる」という比較対象そのものが、上の表の主張だからである。
 */
export function f16AccumulateTruncate(value: number, n: number): number {
  const delta = value / n;
  let acc = 0;
  for (let i = 0; i < n; i++) acc = f16TruncateToZero(acc + delta);
  return acc;
}

/**
 * 実機の相対誤差。**構成上つねに 0 以下**である ── 切り捨ては片側にしか外れない。
 * この一方向性が、監査の「1% 未満」と実測の「−5.2%」を分けていたものである。
 */
export function f16RelativeErrorTruncate(value: number, n: number): number {
  if (!(value > 0)) return 0;
  return (f16AccumulateTruncate(value, n) - value) / value;
}
