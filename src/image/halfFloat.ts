/**
 * half-float の加算累積。**composer のバッファは `HalfFloatType` なので、
 * 加算合成はここで起きていることをそのまま被る。**
 *
 * ## SPEC §4.6 の 2 行を Phase 1b で差し替えた
 *
 * 初版は「**天井は 0.03125 = 2⁻⁵**、停止点は n に依らない」と書いていた。
 * 後半は真だが、前半は **δ ≈ 1.5e−5 における 1 標本**にすぎない。実測（`Float16Array`）:
 *
 * | δ | 実測停止値 | `2048·δ` | 直上の 2 冪 |
 * |---|---|---|---|
 * | 9.537e−7 | 0.001953125 | 0.0019531 | ✓ |
 * | 1.526e−5 | **0.03125** | 0.03125 | ✓ |
 * | 1.530e−5 | **0.0625** | 0.0313344 | ✓ |
 * | 1.000e−3 | 4 | 2.048 | ✓ |
 * | 1.000e+0 | 2048 | 2048 | ✓ |
 *
 * **正しい法則は「天井 = `2048·δ` 以上の最小の 2 冪」。** `A + δ` は
 * `δ = ulp(A)/2` で ties-to-even により丸め戻るので、仮数 10 bit ＝ `ulp(A) = A·2⁻¹⁰`
 * より `A = 2048·δ` が停止点になる。0.03125 はその δ での値でしかない。
 *
 * ## 「約 3% 暗く出る」も偽（実測）
 *
 * 初版は「`dimLevel = 0` の平均色はリニア光で約 3% 暗く出る見込み」と書いていた。
 * **符号も大きさも δ と ulp の 2 進的な関係で決まり、単調でも常に undershoot でもない。**
 * 目標 0.21586（sRGB 128）を n 個に割って足した実測:
 *
 * | n | 合計 | 誤差 |
 * |---|---|---|
 * | 256 | 0.218262 | **+1.11%** |
 * | 378 | 0.219849 | **+1.85%** |
 * | 489 | 0.222168 | **+2.92%** |
 * | 512 | 0.205200 | **−4.94%** |
 * | 2048 | 0.234985 | **+8.86%** |
 * | 3537 | 0.125000 | **−42.09%**（天井で停止） |
 * | 89,208 | 0.007813 | **−96.38%** |
 *
 * 最後の 2 行が Phase 1b の設計を決めている ── **格子（89,208 点）のまま
 * `dimLevel = 0` へ潰すと、加算が天井で止まって 96% 消える。**
 * 列平均バッファが要るのは「丸め誤差 3%」のためではなく、これのためである。
 *
 * ## 予算（ΔE00 換算・グレー軸で実測）
 *
 * | 加算深度の上限 | 最悪 ΔE00 |
 * |---|---|
 * | n ≤ 128 | 0.324 |
 * | n ≤ 256 | 0.622 |
 * | **n ≤ 512** | **1.364** |
 * | n ≤ 1024 | 2.506 |
 * | n ≤ 2048 | **4.376** ← 予算 3.0 を超える |
 *
 * → **加算深度を 512 以下に抑えることが構造的な要件である。**
 */

/** `A + δ` が丸め戻って停止する値。`2048·δ` 以上の最小の 2 冪（実測 15/15 一致） */
export function f16SaturationCeiling(delta: number): number {
  if (!(delta > 0)) return Number.POSITIVE_INFINITY;
  return Math.pow(2, Math.ceil(Math.log2(2048 * delta)));
}

/**
 * 目標値 `value` を `n` 回の等分割で half-float バッファへ足したときの合計。
 *
 * **実際の加算をそのまま回す**（閉形式で近似しない）── 誤差の符号は
 * δ と ulp の 2 進的な関係で決まるので、丸めの規則を書き写した式では再現できない。
 */
export function f16Accumulate(value: number, n: number): number {
  const buf = new Float16Array(1);
  const delta = value / n;
  for (let i = 0; i < n; i++) buf[0] = buf[0] + delta;
  return buf[0];
}

/** 相対誤差。正なら overshoot ── **「暗くなる」と決めつけない** */
export function f16RelativeError(value: number, n: number): number {
  if (!(value > 0)) return 0;
  return (f16Accumulate(value, n) - value) / value;
}
